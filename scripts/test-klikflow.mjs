// Klikt de belangrijkste flow door in headless Chrome tegen de testomgeving (npm run dev:test):
// budget aanmaken in Instellingen, opties wijzigen, bedrag instellen, bladeren en weer verwijderen. Meldt fouten en 500-antwoorden.
//   node scripts/test-klikflow.mjs [http://localhost:5181]

import { spawn } from 'node:child_process';
import { writeFileSync } from "node:fs";
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const base = process.argv[2] ?? 'http://localhost:5181';
const out = join(tmpdir(), 'stax-klikflow');
const profile = mkdtempSync(join(tmpdir(), 'stax-chrome-'));
const chrome = spawn('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', ['--headless=new', '--remote-debugging-port=9336', `--user-data-dir=${profile}`, '--window-size=1440,1000', '--blink-settings=preferredColorScheme=1', 'about:blank'], { stdio: 'ignore' });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await sleep(3000);
const t = (await (await fetch('http://127.0.0.1:9336/json')).json()).find((t) => t.type === 'page');
const ws = new WebSocket(t.webSocketDebuggerUrl); await new Promise((r) => (ws.onopen = r));
let id = 0; const pend = new Map(); const errors = [];
ws.onmessage = (m) => { const d = JSON.parse(m.data); if (d.method === 'Runtime.exceptionThrown') errors.push(d.params.exceptionDetails.exception?.description?.split('\n')[0]); if (d.method === 'Network.responseReceived' && d.params.response.status >= 500) errors.push(`${d.params.response.status} ${d.params.response.url}`); pend.get(d.id)?.(d); pend.delete(d.id); };
const send = (method, params = {}) => new Promise((r) => { pend.set(++id, r); ws.send(JSON.stringify({ id, method, params })); });
const ev = async (e) => (await send('Runtime.evaluate', { expression: e, awaitPromise: true, returnByValue: true })).result?.result?.value;
const shot = async (n) => writeFileSync(`${out}-${n}.png`, Buffer.from((await send('Page.captureScreenshot', { format: 'png' })).result.data, 'base64'));
const click = (sel, text) => ev(`(()=>{const el=[...document.querySelectorAll(${JSON.stringify(sel)})].find(e=>!${JSON.stringify(text ?? '')}||e.textContent.includes(${JSON.stringify(text ?? '')}));if(!el)return 'NIET GEVONDEN';el.click();return 'ok'})()`);
await send('Page.enable'); await send('Runtime.enable'); await send('Network.enable');
await send('Page.navigate', { url: base + '/instellingen/budgetten' }); await sleep(3000);
const row = (name) => `[...document.querySelectorAll('li[data-budget]')].find(l=>l.querySelector('.name')?.textContent==='${name}')`;
console.log('1 budget toevoegen in eerste groep:', await click('.group button.add')); await sleep(500);
await send('Input.insertText', { text: 'Huisdieren' });
console.log('  optie spaart:', await click('.newmap .opt', 'Spaart'));
await shot('1-nieuw');
console.log('  aanmaken:', await click('.newmap button.primary')); await sleep(2500);
console.log('  in de lijst:', await ev(`!!${row('Huisdieren')}`), 'tag:', await ev(`${row('Huisdieren')}?.querySelector('.tag')?.textContent`));
console.log('2 openen:', await ev(`(()=>{const a=${row('Huisdieren')}?.querySelector('a.item'); if(!a) return 'NIET GEVONDEN'; a.click(); return 'ok'})()`)); await sleep(2000);
console.log('  editor open:', await ev(`!!document.querySelector('dialog.sheet[open]')`));
await shot('2-editor');
console.log('  optie doel:', await click('dialog.sheet .opt', 'Doel')); await sleep(300);
await ev(`(()=>{const i=document.querySelector('dialog.sheet input[name=goal]'); i.focus(); })()`);
await send('Input.insertText', { text: '500' });
console.log('  opslaan:', await click('dialog.sheet button.save')); await sleep(2000);
console.log('  editor dicht:', await ev(`!document.querySelector('dialog.sheet[open]')`), 'tag:', await ev(`${row('Huisdieren')}?.querySelector('.tag')?.textContent`));
const newId = await ev(`${row('Huisdieren')}?.dataset.budget`);
await send('Page.navigate', { url: `${base}/map/${newId}` }); await sleep(2500);
console.log('3 detailpagina, soort:', await ev(`document.querySelector('.where')?.textContent.trim()`), 'balk:', await ev(`!!document.querySelector('.periodbar .pick')`));
console.log('  budget aanpassen:', await click('.edit button')); await sleep(400);
await send('Input.insertText', { text: '25' });
console.log('  opslaan:', await click('.pop button.primary')); await sleep(2000);
console.log('  gepland:', await ev(`document.querySelector('.tile strong')?.textContent.trim()`));
await shot('3-detail');
console.log('  volgende budget:', await click('.periodbar .budget a[aria-label^="Volgende"]')); await sleep(2000);
console.log('  url:', await ev('location.pathname'));
console.log('4 instellen:', await click('a.btn', 'Instellen')); await sleep(2500);
await send('Page.navigate', { url: `${base}/instellingen/budgetten?bewerk=${newId}` }); await sleep(2500);
console.log('  verwijderen:', await click('dialog.sheet .ed-foot button', 'Verwijderen')); await sleep(200);
console.log('  ', await click('dialog.sheet button', 'Ja, verwijderen')); await sleep(2500);
console.log('  nog in de lijst:', await ev(`!!${row('Huisdieren')}`));
await send('Page.navigate', { url: base + '/' }); await sleep(2500);
const cell = `[...document.querySelectorAll('.row')].find(r=>r.querySelector('strong')?.textContent==='Boodschappen')?.querySelector('.budgeted button.cell')`;
console.log('5 budget op startscherm:', await ev(`${cell}?.textContent.trim()`), await ev(`(()=>{const b=${cell};if(!b)return 'NIET GEVONDEN';b.click();return 'ok'})()`)); await sleep(300);
await shot('5-popover');
await send('Input.insertText', { text: '280' });
console.log('  alleen deze maand:', await click('.pop .seg button', 'Alleen')); await sleep(100);
console.log('  opslaan:', await click('.pop button.primary')); await sleep(2000);
console.log('  nu:', await ev(`${cell}?.textContent.trim()`), 'url:', await ev('location.pathname'));
await ev(`${cell}.click()`); await sleep(300);
console.log('  terug naar standaard:', await click('.pop button', 'Terug naar standaard')); await sleep(2000);
console.log('  nu:', await ev(`${cell}?.textContent.trim()`));
console.log('fouten:', errors.length ? errors : 'geen');
ws.close(); chrome.kill();
